import {test,expect} from '@playwright/test'
import {login} from './helpers'
import {resolve} from 'node:path'
import {mkdirSync} from 'node:fs'

test('imports a Word document and retains colors, dimensions, images and video through publication',async({page})=>{
 await login(page)
 await expect(page.locator('.category-group').first()).toHaveAttribute('open','')
 await page.getByRole('button',{name:'Новая статья'}).click()
 await page.getByLabel('Название статьи').fill('Импорт Word')
 await page.getByRole('combobox',{name:'Категория',exact:true}).selectOption({label:'Инструкции'})
 await page.getByLabel('Файл Word').setInputFiles(resolve('tests/e2e/fixtures/styled.docx'))
 await expect(page.locator('.tiptap')).toContainText('Документ из Word')
 await expect(page.locator('.tiptap table')).toContainText('Цветная ячейка')
 await expect(page.locator('.tiptap ol')).toContainText('Второй пункт')
 await expect(page.locator('.tiptap img')).toHaveAttribute('src',/^\/media\//)
 await expect(page.locator('.tiptap video')).toHaveAttribute('src','https://example.com/training.mp4')
 await page.getByRole('button',{name:'Опубликовать',exact:true}).click()
 await expect(page).toHaveURL(/\/articles\//)
 await expect(page.locator('.article-body')).toContainText('Документ из Word')
 await expect(page.locator('.article-body span').filter({hasText:'Цветной текст'})).toHaveCSS('color','rgb(18, 52, 86)')
 await expect(page.locator('.article-body span').filter({hasText:'Цветной текст'})).toHaveCSS('background-color','rgb(255, 255, 0)')
 const cell=page.locator('.article-body td').first()
 await expect(cell).toHaveCSS('background-color','rgb(17, 34, 51)')
 await expect(cell).toHaveAttribute('style',/width:180px/)
 await expect(cell).toHaveAttribute('style',/height:64px/)
 await expect(page.locator('.article-body video')).toHaveAttribute('src','https://example.com/training.mp4')
 await expect(page.locator('.article-body img')).toBeVisible()
 await page.getByRole('button',{name:'Редактировать',exact:true}).click()
 await expect(page.locator('.tiptap')).toContainText('Цветной текст')
 await expect(page.locator('.tiptap video')).toHaveAttribute('src','https://example.com/training.mp4')
})

test('toolbar remains reachable while editing a long article and dimensions persist',async({page})=>{
 await login(page)
 await page.getByRole('button',{name:'Новая статья'}).click()
 await page.getByLabel('Название статьи').fill('Длинная статья')
 await page.getByRole('combobox',{name:'Категория',exact:true}).selectOption({label:'Инструкции'})
 await page.locator('.tiptap').fill(('Строка текста\n').repeat(100))
 await page.locator('.tiptap').press('Control+End')
 await page.getByRole('button',{name:'Вставить таблицу',exact:true}).click()
 await page.locator('.tiptap th').first().click()
 await page.getByLabel('Ширина столбца, px').fill('220')
 await page.getByLabel('Ширина столбца, px').press('Enter')
 await page.getByLabel('Высота строки, px').fill('80')
 await page.getByLabel('Высота строки, px').press('Enter')
 const toolbar=page.getByRole('toolbar')
 await page.locator('.tiptap tr').last().scrollIntoViewIfNeeded()
 const box=await toolbar.boundingBox()
 expect(box!.y).toBeGreaterThanOrEqual(0)
 expect(box!.y+box!.height).toBeLessThan(720)
 mkdirSync('.validation',{recursive:true})
 await page.screenshot({path:'.validation/editor-desktop.png'})
 await page.setViewportSize({width:390,height:844})
 await page.locator('.tiptap tr').last().scrollIntoViewIfNeeded()
 const mobileBox=await toolbar.boundingBox()
 expect(mobileBox!.y).toBeGreaterThanOrEqual(0)
 expect(mobileBox!.y+mobileBox!.height).toBeLessThan(844)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.screenshot({path:'.validation/editor-mobile.png'})
 await page.getByRole('button',{name:'Опубликовать',exact:true}).click()
 await expect(page).toHaveURL(/\/articles\//)
 await expect(page.locator('.article-body th').first()).toHaveAttribute('style',/width:220px/)
 await expect(page.locator('.article-body th').first()).toHaveAttribute('style',/height:80px/)
})

