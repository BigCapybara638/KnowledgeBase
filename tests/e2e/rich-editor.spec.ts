test('uploaded video plays and remains protected after publication',async({page,browser})=>{
 await login(page)
 await page.getByRole('button',{name:'Новая статья'}).click()
 await page.getByLabel('Название статьи').fill('Видео из файла')
 await page.getByRole('combobox',{name:'Категория',exact:true}).selectOption({label:'Инструкции'})
 await page.getByLabel('Файл видео').setInputFiles(resolve('tests/e2e/fixtures/clip.webm'))
 await expect(page.locator('.tiptap video')).toHaveAttribute('src',/^\/media\//)
 await page.getByRole('button',{name:'Опубликовать',exact:true}).click()
 await expect(page).toHaveURL(/\/articles\//)
 const video=page.locator('.article-body video')
 await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.duration)).toBeGreaterThan(0)
 const src=await video.getAttribute('src')
 const guest=await browser.newContext({baseURL:'http://127.0.0.1:4173'})
 const response=await guest.request.get(src!,{maxRedirects:0})
 expect(response.status()).not.toBe(200)
 await guest.close()
})

test('pasted Word HTML retains text colors, cell formatting and video links',async({page})=>{
 await login(page)
 await page.getByRole('button',{name:'Новая статья'}).click()
 await page.getByLabel('Название статьи').fill('Вставка из Word')
 await page.getByRole('combobox',{name:'Категория',exact:true}).selectOption({label:'Инструкции'})
 await page.locator('.tiptap').focus()
 await page.locator('.tiptap').evaluate(element=>{
  const data=new DataTransfer()
  data.setData('text/html','<p style="color:rgb(18,52,86);background-color:#ffff00"><strong>Вставленный текст</strong></p><table><tr><td style="width:140px;height:70px;background-color:#112233"><p>Ячейка из Word</p></td></tr></table><video controls src="https://example.com/clip.mp4"></video>')
  element.dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}))
 })
 await expect(page.locator('.tiptap table')).toContainText('Ячейка из Word')
 await page.getByRole('button',{name:'Опубликовать',exact:true}).click()
 await expect(page).toHaveURL(/\/articles\//)
 await expect(page.locator('.article-body span').filter({hasText:'Вставленный текст'})).toHaveCSS('color','rgb(18, 52, 86)')
 await expect(page.locator('.article-body td')).toHaveCSS('background-color','rgb(17, 34, 51)')
 await expect(page.locator('.article-body td')).toHaveAttribute('style',/width:140px/)
 await expect(page.locator('.article-body video')).toHaveAttribute('src','https://example.com/clip.mp4')
})

test('reports unsupported local video when pasting Word HTML',async({page})=>{
 await login(page)
 await page.getByRole('button',{name:'Новая статья'}).click()
 await page.locator('.tiptap').focus()
 await page.locator('.tiptap').evaluate(element=>{
  const data=new DataTransfer();data.setData('text/html','<p>Текст с видео</p><video src="file:///C:/clip.mp4"></video>')
  element.dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}))
 })
 await expect(page.locator('.tiptap')).toContainText('Текст с видео')
 await expect(page.locator('#editor-notice')).toContainText(/видео/i)
})

test('merged table cells copied from Word remain publishable',async({page})=>{
 await login(page)
 await page.getByRole('button',{name:'Новая статья'}).click()
 await page.getByLabel('Название статьи').fill('Объединённые ячейки Word')
 await page.getByRole('combobox',{name:'Категория',exact:true}).selectOption({label:'Инструкции'})
 await page.locator('.tiptap').focus()
 await page.locator('.tiptap').evaluate(element=>{
  const data=new DataTransfer();data.setData('text/html','<table><tr><td colspan="2" style="width:240px;height:70px"><p>Общая ячейка</p></td></tr><tr><td><p>Левая</p></td><td><p>Правая</p></td></tr></table>')
  element.dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}))
 })
 await expect(page.locator('.tiptap td').first()).toHaveAttribute('colspan','2')
 await page.getByRole('button',{name:'Опубликовать',exact:true}).click()
 await expect(page).toHaveURL(/\/articles\//)
 await expect(page.locator('.article-body td').first()).toHaveAttribute('colspan','2')
})
