import {test,expect} from '@playwright/test'
import {login} from './helpers'

test('follows system appearance with the main app palette without a reload',async({page})=>{
 await page.emulateMedia({colorScheme:'light'})
 await page.goto('/login')
 const root=page.locator('html'),topbar=page.locator('.topbar'),logo=page.locator('.brand-logo')
 await expect(root).toHaveCSS('background-color','rgb(245, 247, 250)')
 await expect(root).toHaveCSS('color','rgb(26, 28, 30)')
 await expect(topbar).toHaveCount(0)
 await expect(page.locator('.auth-wrap')).toHaveCSS('background-image','none')
 await expect(page.locator('.auth-wrap')).toHaveCSS('background-color','rgb(245, 247, 250)')
 await expect(page.getByLabel('Логин',{exact:true})).toHaveCSS('background-color','rgb(255, 255, 255)')
 await expect(page.getByRole('button',{name:'Войти',exact:true})).toHaveCSS('background-color','rgb(0, 123, 255)')
 await expect(page.getByRole('button',{name:'Войти',exact:true})).toHaveCSS('color','rgb(255, 255, 255)')
 await page.emulateMedia({colorScheme:'dark'})
 await expect(root).toHaveCSS('background-color','rgb(26, 28, 30)')
 await expect(root).toHaveCSS('color','rgb(226, 226, 230)')
 await expect(topbar).toHaveCount(0)
 await expect(page.locator('.auth-wrap')).toHaveCSS('background-image','none')
 await expect(page.locator('.auth-wrap')).toHaveCSS('background-color','rgb(26, 28, 30)')
 await expect(page.getByRole('button',{name:'Войти',exact:true})).toHaveCSS('background-color','rgb(173, 198, 255)')
 await expect(page.getByRole('button',{name:'Войти',exact:true})).toHaveCSS('color','rgb(0, 46, 105)')
 await login(page)
 await expect(topbar).toHaveCSS('background-color','rgb(36, 38, 41)')
 await expect(logo).toHaveCSS('filter','invert(1)')
 await expect(logo).toBeVisible()
 await expect(page.locator('.brand')).toHaveText('')
 await expect(page.getByRole('link',{name:'Axentris',exact:true})).toHaveAttribute('href','/')
 await expect(page.locator('.sidebar')).toHaveCSS('background-color','rgb(36, 38, 41)')
 await page.getByRole('button',{name:'Новая статья'}).click()
 const title=page.getByLabel('Название статьи'),category=page.getByRole('combobox',{name:'Категория',exact:true}),toolbar=page.getByRole('toolbar')
 await title.fill('Проверка темы')
 await page.locator('.tiptap').fill('Текст остаётся при смене темы')
 await expect(page.locator('.editor-panel')).toHaveCSS('background-color','rgb(36, 38, 41)')
 await expect(toolbar).toHaveCSS('background-color','rgb(26, 28, 30)')
 await page.emulateMedia({colorScheme:'light'})
 await expect(topbar).toHaveCSS('background-color','rgb(255, 255, 255)')
 await expect(logo).toHaveCSS('filter','none')
 await expect(page.locator('.editor-panel')).toHaveCSS('background-color','rgb(255, 255, 255)')
 await expect(toolbar).toHaveCSS('background-color','rgb(245, 247, 250)')
 await expect(title).toHaveCSS('background-color','rgb(255, 255, 255)')
 await expect(category).toHaveCSS('background-color','rgb(255, 255, 255)')
 await expect(page.locator('.tiptap')).toHaveText('Текст остаётся при смене темы')
 await expect(title).toHaveValue('Проверка темы')
 await page.emulateMedia({colorScheme:'dark'})
 await expect(toolbar).toHaveCSS('background-color','rgb(26, 28, 30)')
})
